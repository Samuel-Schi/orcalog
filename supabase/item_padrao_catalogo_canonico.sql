CREATE TABLE IF NOT EXISTS public.item_padrao (
  codigo        text PRIMARY KEY,
  nome_canonico text NOT NULL,
  nome_norm     text NOT NULL,
  tipo          text NOT NULL DEFAULT 'PECA',
  ativo         boolean NOT NULL DEFAULT true
);
CREATE TABLE IF NOT EXISTS public.item_padrao_linha (
  codigo text NOT NULL REFERENCES public.item_padrao(codigo) ON DELETE CASCADE,
  linha  text NOT NULL,
  PRIMARY KEY (codigo, linha)
);
CREATE TABLE IF NOT EXISTS public.item_alias (
  alias_norm text PRIMARY KEY,
  alias      text NOT NULL,
  codigo     text NOT NULL REFERENCES public.item_padrao(codigo) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS ix_item_alias_codigo ON public.item_alias(codigo);
